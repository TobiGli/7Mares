create table if not exists public.boats (
  id bigint generated by default as identity primary key,
  name text not null,
  type text not null check (type in ('Yates', 'Lanchas', 'Veleros', 'Catamaranes', 'Botes', 'Motos acuaticas')),
  location text not null,
  price numeric(12, 2) not null check (price >= 0),
  year integer not null,
  length text,
  cabins integer default 0,
  image_url text not null,
  tag text,
  featured boolean default false,
  created_at timestamptz default now()
);

alter table public.boats enable row level security;
drop policy if exists "Public can read boats" on public.boats;
create policy "Public can read boats" on public.boats for select using (true);

