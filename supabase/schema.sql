create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  full_name text,
  role text not null default 'buyer' check (role in ('buyer', 'admin')),
  created_at timestamptz default now()
);

alter table public.profiles enable row level security;
drop policy if exists "Users can read their profile" on public.profiles;
create policy "Users can read their profile" on public.profiles for select using (auth.uid() = id);

create or replace function public.is_admin()
returns boolean
language sql
security definer
set search_path = public
stable
as $$
  select exists (select 1 from public.profiles where id = auth.uid() and role = 'admin');
$$;

revoke all on function public.is_admin() from public;
grant execute on function public.is_admin() to authenticated;

create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  insert into public.profiles (id, full_name) values (new.id, new.raw_user_meta_data ->> 'full_name');
  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
  after insert on auth.users
  for each row execute procedure public.handle_new_user();

drop policy if exists "Admins can create boats" on public.boats;
create policy "Admins can create boats" on public.boats for insert with check (public.is_admin());
drop policy if exists "Admins can update boats" on public.boats;
create policy "Admins can update boats" on public.boats for update using (public.is_admin()) with check (public.is_admin());
drop policy if exists "Admins can delete boats" on public.boats;
create policy "Admins can delete boats" on public.boats for delete using (public.is_admin());

alter table public.boats add column if not exists updated_at timestamptz default now();

create or replace function public.set_boat_updated_at()
returns trigger
language plpgsql
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

drop trigger if exists set_boats_updated_at on public.boats;
create trigger set_boats_updated_at
  before update on public.boats
  for each row execute procedure public.set_boat_updated_at();

create index if not exists boats_type_idx on public.boats(type);
create index if not exists boats_featured_idx on public.boats(featured) where featured = true;
create index if not exists boats_created_at_idx on public.boats(created_at desc);

create table if not exists public.favorites (
  user_id uuid references auth.users(id) on delete cascade,
  boat_id bigint references public.boats(id) on delete cascade,
  created_at timestamptz default now(),
  primary key (user_id, boat_id)
);

alter table public.favorites enable row level security;
drop policy if exists "Users manage own favorites" on public.favorites;
create policy "Users manage own favorites" on public.favorites for all using (auth.uid() = user_id) with check (auth.uid() = user_id);
create index if not exists favorites_boat_id_idx on public.favorites(boat_id);

create table if not exists public.analytics_events (
  id bigint generated by default as identity primary key,
  event_name text not null,
  boat_id bigint references public.boats(id) on delete set null,
  user_id uuid references auth.users(id) on delete set null,
  metadata jsonb default '{}'::jsonb,
  created_at timestamptz default now()
);

alter table public.analytics_events enable row level security;
drop policy if exists "Visitors can create analytics events" on public.analytics_events;
create policy "Visitors can create analytics events" on public.analytics_events for insert with check (user_id is null or auth.uid() = user_id);
drop policy if exists "Admins can read analytics events" on public.analytics_events;
create policy "Admins can read analytics events" on public.analytics_events for select using (public.is_admin());
create index if not exists analytics_events_created_at_idx on public.analytics_events(created_at desc);
create index if not exists analytics_events_boat_id_idx on public.analytics_events(boat_id);
